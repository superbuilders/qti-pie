/**
 * The registry's own seed: the tables the general-purpose primitives read and which table each reads in each role, as
 * relational rows every installation carries (the lead's ruling of 2026-11-21, a hard cutover: the generic operators'
 * facts are qti-pie's and live beside their SQL). They describe and serve this registry's own classes
 * (`#ledger/registry/operators.ts`): the spellings of units, the units a single letter names, the spellings a mistyped
 * unit is measured against, the words a unit competes with or is glued to, English plurals, and the words
 * `phrase-distance`'s noun typo reads; and the measure words a converter's asked-unit derivation reads. A deployment's
 * roster appends its own tables and bindings after these (`registryOf`), never in place of them: an application's own
 * vocabulary is its own (AlphaTest's capital-I spellings of lb are metis's).
 *
 * Each row is at its place as `@metis/alphatest-operators`' former seed numbered it, so a deployment's rows appended to
 * one of these tables keep theirs and the tables read in the order they did. The rows are the package agent's ruled
 * split (impl/IMPL-OPS/seed-split/seed-split.md, sha256 0ef4168ec6169314…): each kept here because an
 * installation that is no AlphaTest one needs it.
 *
 * @module
 */
import { Option } from "effect"
import type { SeedEntry, TableBinding } from "#ledger/registry/contract.ts"

/**
 * A list table's entries: each its key, at its place in the table's order.
 *
 * @param table - The table's name.
 * @param entries - Its places and keys, in order.
 * @returns Its entries.
 */
const listTable = (table: string, entries: readonly (readonly [number, string])[]): readonly SeedEntry[] =>
	entries.map(([place, key]) => ({ key, place, table, value: Option.none() }))

/**
 * A map table's entries: each its key and the value it maps it to, at its place in the table's order.
 *
 * @param table - The table's name.
 * @param entries - Its places, keys and values, in order.
 * @returns Its entries.
 */
const mapTable = (
	table: string,
	entries: readonly (readonly [number, string, string])[]
): readonly SeedEntry[] => entries.map(([place, key, value]) => ({ key, place, table, value: Option.some(value) }))

