/**
 * Write `src/templates.generated.ts`: the six published response-processing templates as element
 * trees, read from `templates/` by crust. Run it after a template file changes; `templates.test.ts`
 * fails while the module and the files disagree.
 *
 * @module
 */
import path from "node:path";
import * as NodeRuntime from "@effect/platform-node/NodeRuntime";
import * as NodeServices from "@effect/platform-node/NodeServices";
import { Effect, FileSystem } from "effect";
import { readTemplates } from "#processing/test/templates.ts";

const generated = path.resolve(import.meta.dirname, "..", "src", "templates.generated.ts");

const program = Effect.gen(function* generateTemplates() {
  const fs = yield* FileSystem.FileSystem;
  const trees = yield* readTemplates();
  yield* fs.writeFileString(
    generated,
    [
      "/**",
      " * The six published response-processing templates (information model §2.5.1, reading `built-in-templates`), compiled in:",
      " * each template's published file under `templates/` as the element tree the compiler reads. Generated by",
      " * `tools/generate-templates.ts`; `templates.test.ts` holds it to the files.",
      " *",
      " * @module",
      " */",
      'import type { XmlElement } from "#processing/xml.ts";',
      "",
      "/**",
      " * Each published template's `qti-response-processing`, by name.",
      " */",
      `export const publishedTemplates = ${JSON.stringify(trees)} as const satisfies Readonly<Record<string, XmlElement>>;`,
      "",
    ].join("\n"),
  );
});

NodeRuntime.runMain(program.pipe(Effect.provide(NodeServices.layer)));
