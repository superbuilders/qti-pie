/**
 * Generate Alpha's PCI modules: each module file, `pci-modules/<id>.js`, its typed source
 * `pci-modules/<id>.ts` with the types stripped by the machine's Node (`stripTypeScriptTypes`,
 * strip mode), as `#plate/alpha/pci-modules.ts` says why; and `pci-module-pins.generated.ts`, each
 * file's SHA-256 as Subresource Integrity writes it, which `#plate/alpha/pci-modules.test.ts` holds
 * every file to. Both are generated, so a car that changes a module never edits a pin by hand, and
 * two cars that change different modules regenerate the table rather than conflict on it.
 *
 * Run from plate's directory: `pnpm run generate:alpha-pci-modules`.
 *
 * @module
 */
import { regex } from "arkregex";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { stripTypeScriptTypes } from "node:module";
import path from "node:path";

/**
 * Each module source, by its path in `alpha/`: the entries of `alpha/` in `pci-modules/` that are
 * TypeScript, so a folder that holds no module yet generates nothing.
 */
const sources = readdirSync(import.meta.dirname, { recursive: true })
  .map(String)
  .filter((entry) => path.dirname(entry) === "pci-modules" && path.extname(entry) === ".ts")
  .toSorted();

/**
 * Each module's pin, by its id, in the sources' order.
 */
const pins = sources.map((source) => {
  const script = stripTypeScriptTypes(
    readFileSync(path.join(import.meta.dirname, source), "utf-8"),
  );

  writeFileSync(
    path.join(import.meta.dirname, source.replace(regex("\\.ts$", "u"), ".js")),
    script,
  );

  return [
    path.basename(source, ".ts"),
    `sha256-${createHash("sha256").update(script).digest("base64")}`,
  ] as const;
});

writeFileSync(
  path.join(import.meta.dirname, "pci-module-pins.generated.ts"),
  [
    "/**",
    " * Each Alpha PCI module file's SHA-256, base64, as Subresource Integrity writes it, by the module's",
    " * id. Generated by `generate-pci-modules.ts`; `pci-modules.test.ts` holds every file to it.",
    " *",
    " * @module",
    " */",
    'import type { AlphaPciModuleId } from "#plate/alpha/pci-modules.ts";',
    "",
    "/**",
    " * Each module file's pin, by its id.",
    " */",
    "export const pinned: Readonly<Record<AlphaPciModuleId, string>> = {",
    ...pins.map(([id, pin]) => `  ${JSON.stringify(id)}: ${JSON.stringify(pin)},`),
    "};",
    "",
  ].join("\n"),
);
